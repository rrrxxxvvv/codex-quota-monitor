const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {transition}=require('../quota-core.cjs');
const result=(used,reset,account='a',secondary=null)=>({accountId:account,rateLimitsByLimitId:{codex:{primary:{usedPercent:used,resetsAt:reset,windowDurationMins:300},secondary}}});
let s=transition(null,result(100,1000),900000);
assert.equal(s.pending.length,0,'first read is baseline');
assert.equal(transition(s,result(100,1000),1100000).pending.length,0,'clock alone never triggers');
assert.equal(transition(s,result(100,2000),900000).pending.length,0,'future timestamp change alone never triggers');
let t=transition(s,result(3,2000),1100000);
assert.equal(t.pending.length,1,'confirmed reset triggers once');
assert.equal(t.pending[0].kind,'额度周期已重置');
assert.equal(transition(t,result(3,2000),1200000).pending.length,1,'unchanged state does not duplicate');
t.pending=[];
assert.equal(transition(t,result(5,2000),1300000).pending.length,0,'acknowledged reset does not return');
assert.equal(transition(s,result(20,1000),950000).pending[0].kind,'可用额度已增加','manual/rolling recovery is labeled honestly');
assert.equal(transition(s,result(0,2000,'b'),1100000).pending.length,0,'account switch baselines');
assert.throws(()=>transition(s,{accountId:'a',rateLimitsByLimitId:{}},1100000));
assert.throws(()=>transition(s,{rateLimits:result(1,2).rateLimitsByLimitId.codex}));
const secondary={usedPercent:80,resetsAt:9000,windowDurationMins:10080};
s=transition(null,result(100,1000,'a',secondary),900000);
t=transition(s,result(0,2000,'a',{...secondary,usedPercent:0}),1100000);
assert.equal(t.pending.length,2,'independent windows detected');
const restored=JSON.parse(JSON.stringify(t));
assert.equal(transition(restored,result(0,2000,'a',{...secondary,usedPercent:0}),1200000).pending.length,2,'pending reminders survive restart');
// Windows PowerShell 5.1 requires a UTF-8 BOM for Chinese source text.
const file=path.resolve(__dirname,'../Monitor.ps1');
const text=fs.readFileSync(file,'utf8').replace(/^\uFEFF/,'');
fs.writeFileSync(file,'\uFEFF'+text);
console.log('PASS: baseline, confirmed reset, clock-only, future timestamp, deduplication, acknowledgment, recovery, account changes, missing data, multiple windows, restart persistence.');
